/** Get courses by programme type, level, and optional semester. */
export function getCoursesByProgramme(
  programmeType: string,
  level: number | string,
  semester?: string,
): FuekCourse[] {
  return ALL_FUEK_COURSES.filter(
    (c) =>
      c.programmeType === programmeType &&
      c.level === level &&
      (!semester || c.semester === semester || c.semester === "Both"),
  );
}

/** Get only compulsory courses for a programme + level. */
export function getCompulsoryCourses(
  programmeType: string,
  level: number | string,
  semester?: string,
): FuekCourse[] {
  return getCoursesByProgramme(programmeType, level, semester).filter(
    (c) => c.type === "compulsory",
  );
}

/** Get only elective courses for a programme + level. */
export function getElectiveCourses(
  programmeType: string,
  level: number | string,
  semester?: string,
): FuekCourse[] {
  return getCoursesByProgramme(programmeType, level, semester).filter(
    (c) => c.type === "elective",
  );
}

/** Get all GST courses at a given level. */
export function getGSTCourses(level: number | string): FuekCourse[] {
  return ALL_FUEK_COURSES.filter((c) => c.isGST && c.level === level);
}

/** Get prerequisite codes for a given course code. */
export function getCoursePrerequisites(courseCode: string): string[] {
  const normalized = courseCode.replace(/\s+/g, " ").trim();
  const course = ALL_FUEK_COURSES.find(
    (c) => c.code.replace(/\s+/g, " ").trim() === normalized,
  );
  return course?.prerequisites ?? [];
}

/** Sum total credit units from a list of courses. */
export function getTotalCreditUnits(courses: FuekCourse[]): number {
  return courses.reduce((sum, c) => sum + c.creditUnits, 0);
}

/** Validate whether selected courses satisfy FUEK credit unit rules. */
export function validateCreditUnits(courses: FuekCourse[]): {
  valid: boolean;
  total: number;
  min: number;
  max: number;
  message: string;
} {
  const total = getTotalCreditUnits(courses);
  const { minCreditUnits: min, maxCreditUnits: max } = REGISTRATION_RULES;
  if (total < min) {
    return {
      valid: false,
      total,
      min,
      max,
      message: `You have registered ${total} credit units. Minimum required is ${min}.`,
    };
  }
  if (total > max) {
    return {
      valid: false,
      total,
      min,
      max,
      message: `You have registered ${total} credit units. Maximum allowed is ${max}.`,
    };
  }
  return {
    valid: true,
    total,
    min,
    max,
    message: `Valid registration: ${total} credit units (between ${min} and ${max}).`,
  };
}
