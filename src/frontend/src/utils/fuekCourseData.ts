export function getCombinationPairs(): FuekCombinationPair[] {
  return FUEK_COMBINATION_PAIRS;
}

/** Get courses by department name, level, and semester for BSc-Ed programmes. */
export function getCoursesByDepartment(
  department: "Computer Science" | "Biology",
  level: number,
  semester: string,
): FuekCourse[] {
  const pool =
    department === "Computer Science" ? FUEK_CSC_COURSES : FUEK_BIO_COURSES;
  return pool.filter(
    (c) =>
      c.level === level && (c.semester === semester || c.semester === "Both"),
  );
}

