/** Get courses by department name, level, and semester for BSc-Ed programmes. */
export function getCoursesByDepartment(
  department:
    | "Computer Science"
    | "Biology"
    | "Chemistry"
    | "Integrated Science"
    | "Mathematics"
    | "Education & Mathematics"
    | "Environmental Education",
  level: number,
  semester: string,
): FuekCourse[] {
  let pool: FuekCourse[];
  if (department === "Computer Science") pool = FUEK_CSC_COURSES;
  else if (department === "Biology") pool = FUEK_BIO_COURSES;
  else if (department === "Chemistry") pool = FUEK_CHM_COURSES;
  else if (
    department === "Mathematics" ||
    department === "Education & Mathematics"
  )
    pool = FUEK_MTH_COURSES;
  else if (department === "Environmental Education") pool = FUEK_EED_COURSES;
  else pool = FUEK_EIS_COURSES;
  return pool.filter(
    (c) =>
      c.level === level && (c.semester === semester || c.semester === "Both"),
  );
}

